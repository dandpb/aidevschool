_TS_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _render_key(key: str) -> str:
    return key if _TS_IDENTIFIER.fullmatch(key) else json.dumps(key, ensure_ascii=False)


