_REVIEW_REASON_DECL = 'export type ReviewReason = "due" | "overdue" | "interleaving" | "recurring-trap"'


def _review_slice_type_lines(*, with_game_key: bool) -> list[str]:
    """The shared ``ReviewSlice`` type declaration for voxelDojo slice files.

    ``with_game_key`` adds the ``gameId``/``unitId`` fields of the per-game
    variant. Both renderers emit from this one body so the type cannot drift
    between the legacy shared file and the per-game fan-out files.
    """
    lines = ["export type ReviewSlice = {"]
    if with_game_key:
        lines.append("  readonly gameId: string")
        lines.append("  readonly unitId: string")
    lines += [
        "  readonly nextReviews: ReadonlyArray<{",
        "    readonly unitId: string",
        "    readonly title: string",
        "    readonly dueIn: string",
        "    readonly reason: ReviewReason",
        "  }>",
        "  readonly streak: {",
        "    readonly current: number",
        "    readonly longest: number",
        "    readonly lastGateDate: string | null",
        "    readonly freezesEquipped: number",
        "    readonly freezesMax: number",
        "  }",
        "}",
    ]
    return lines


