def compile_competency_map(track_dir, outdir, validated=None):
    """Compila o read model opcional de competências. Retorna (errors, output_path).

    Fail closed: só gera artefato com validação verde (schema + semântica);
    qualquer erro devolve os erros e nenhum arquivo é escrito. `validated` é
    a tupla já computada de validate_track(track_dir), para não revalidar.
    """
    errors, ready_lessons, catalog = (
        validated if validated is not None else validate_track(track_dir)
    )
    if errors:
        return errors, None
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    out_path = outdir / COMPETENCY_MAP_FILENAME
    out_path.write_text(_render_competency_map(catalog, ready_lessons), encoding="utf-8")
    return [], out_path
