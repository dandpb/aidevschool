_GLOSSARY_IDS = {entry["id"] for entry in GLOSSARY}


def _mapping(competency):
    """Projeta o objeto canônico `competency` (primary + supporting[]) no
    formato do read model. IDs fora do glossário já foram rejeitados pela
    validação de schema antes de chegar aqui (fail closed upstream)."""
    if competency is None:
        return None
    primary = competency["primary"]
    supporting = list(competency.get("supporting") or [])
    assert primary in _GLOSSARY_IDS, "primary fora do glossário: %r" % primary
    for supporting_id in supporting:
        assert supporting_id in _GLOSSARY_IDS, "supporting fora do glossário: %r" % supporting_id
    return {"primary": primary, "supporting": supporting}


def _lesson_entry(lesson, journey_by_module, order_by_module):
    return {
        "lessonId": lesson["id"],
        "moduleId": lesson["moduleId"],
        "journey": journey_by_module[lesson["moduleId"]],
        "order": order_by_module[lesson["moduleId"]],
        "prerequisites": list(lesson.get("prerequisites") or []),
        "mapping": _mapping(lesson.get("competency")),
    }


def _competency_payload(catalog, ready_lessons):
    """Ordenação documental idêntica ao read model de lições: módulos por
    `order` crescente e lições na ordem do catálogo dentro do módulo. Apenas
    lições ready (com arquivo validado) entram — planned continua fora, como
    em lessons.ts. O filtro de jornada NÃO é aplicado aqui (decisão AID-3453
    R6: visibilidade permanece no adaptador consumidor)."""
    modules = sorted(catalog.get("modules") or [], key=lambda module: module.get("order", 0))
    journey_by_module = {module["id"]: module["journey"] for module in modules}
    order_by_module = {module["id"]: module.get("order", 0) for module in modules}
    ready_by_id = {lesson["id"]: lesson for lesson in ready_lessons}
    entries = []
    for module in modules:
        for entry in catalog.get("lessons") or []:
            if entry["moduleId"] != module["id"]:
                continue
            lesson = ready_by_id.get(entry["id"])
            if lesson is None:
                continue
            entries.append(_lesson_entry(lesson, journey_by_module, order_by_module))
    return entries


def _as_ts(payload):
    return json.dumps(payload, ensure_ascii=False, indent=2)


